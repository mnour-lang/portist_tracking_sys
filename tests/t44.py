import os;APP='file://'+os.environ.get('PST_HTML',os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','portist_invoice.html'))
from playwright.sync_api import sync_playwright
ok=lambda n,v:print(('PASS ' if v else 'FAIL ')+n)
with sync_playwright() as p:
    b=p.chromium.launch();pg=b.new_page(viewport={'width':1300,'height':900});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(APP);pg.wait_for_timeout(400)
    pg.fill('#lgName','م');pg.fill('#lgUser','admin');pg.fill('#lgPass','secret1');pg.fill('#lgPass2','secret1');pg.click('#lgGo');pg.wait_for_timeout(600)
    # settings: currency table, inverse entry
    pg.evaluate("routeTo('#/settings')");pg.wait_for_timeout(300)
    pg.click('#gNav [data-g=gen]');pg.select_option('#gFxDir','i');pg.wait_for_timeout(300)
    ok('flag stored',pg.evaluate("FXD()"))
    pg.click('#gNav [data-g=cur]')
    ok('header says units per 1 USD',pg.evaluate("$('gCur').textContent.includes('عدد الوحدات لكل 1 دولار')"))
    inp="#gCur tr:has(input[value=TRY]) input[data-cf=rate]"
    pg.fill(inp,'36.5');pg.dispatch_event(inp,'change');pg.wait_for_timeout(300)
    canon=pg.evaluate("curGet('₺').rate")
    ok('stored canonically as USD per TRY (~0.0274)',abs(float(canon)-1/36.5)<1e-8)
    ok('displayed back as 36.5',pg.input_value(inp)=='36.5')
    ok('curRate USD->TRY = 36.5',abs(pg.evaluate("curRate('$','₺')")-36.5)<1e-6)
    pg.evaluate("curSet()")
    pg.click('#gCur .fxSw');pg.wait_for_timeout(300)
    ok('flip back to direct shows 0.0274',abs(float(pg.input_value(inp))-0.0274)<1e-4 and not pg.evaluate("FXD()"))
    ok('select follows',pg.input_value('#gFxDir')=='d')
    # invoice: 1 USD = ? TRY entry stores canonical
    pg.evaluate("localStorage.setItem('pst_fxdir','i');setMode('i')");pg.wait_for_timeout(300)
    pg.evaluate("$('cur').value='$';$('cur2').value='₺';")
    pg.fill('#rate','0.025');pg.wait_for_timeout(200)
    ok('invoice label inverse "1 ₺ = ? $"',pg.evaluate("$('rateLbl').textContent").find('1 ₺ = ? $')>=0)
    ok('snap rate canonical 1 USD = 40 TRY',pg.evaluate("snap().rate")=='40')
    pg.evaluate("localStorage.setItem('pst_fxdir','d')")
    pg.fill('#rate','0.05');pg.evaluate("calc()")
    ok('direct snap keeps text',pg.evaluate("snap().rate")=='0.05')
    pg.click('#bInvSw, .cur .fxSw');pg.wait_for_timeout(200)
    ok('flip on invoice converts field 0.05 -> 20 and label',pg.input_value('#rate')=='20' and pg.evaluate("snap().rate")=='0.05')
    pg.click('.cur .fxSw');ok('flip back',pg.input_value('#rate')=='0.05')
    # cost modal in inverse
    pg.evaluate("""()=>{LS.set('pst_revpol','inv');SHS.set({'SH-1':{code:'SH-1',cur:'$',date:'2026-01-01',st:'ld',hist:[],costs:[],cons:[{id:'c1',cust:'A',cbm:1,pk:1}]}})}""")
    pg.evaluate("localStorage.setItem('pst_fxdir','i');routeTo('#/costs/shipment/SH-1')");pg.wait_for_timeout(800)
    pg.evaluate("ccModal('SH-1','')");pg.wait_for_timeout(300)
    pg.select_option('#cc_cur','₺');pg.wait_for_timeout(200)
    pg.fill('#cc_amt','3650');pg.fill('#cc_fx','36.5')
    ok('hint inverse',pg.evaluate("$('cc_hint').textContent").find('1 $ = ? ₺')>=0)
    pg.click('#cc_save');pg.wait_for_timeout(900)
    c=pg.evaluate("SHS.get()['SH-1'].costs[0]")
    ok('cost fx stored canonical (1 TRY = 1/36.5 USD)',abs(float(c['fx'])-1/36.5)<1e-8)
    T=pg.evaluate("shFin(SHS.get()['SH-1']).T")
    ok('cost equals 100 USD',abs(T['cost']-100)<0.02)
    pg.evaluate("ccModal('SH-1','%s')"%c['id']);pg.wait_for_timeout(300)
    ok('editing shows 36.5 again',pg.input_value('#cc_fx')=='36.5')
    # receipts: inverse entry in allocation table
    pg.evaluate("localStorage.setItem('pst_fxdir','d')")
    pg.evaluate("""()=>{const inv={'PST-0001':{rcv:'A',st:'sent',t:1000,pd:0,cur:'$',date:'2026-01-02'}};LS.set('pst_inv',inv);ALL={I:inv,Rc:{}};IXV++;const M=curMap();M['€'].on=1;M['€'].rate='1.1';curSave(M)}""")
    pg.evaluate("setMode('r');rnew()");pg.wait_for_timeout(300)
    pg.evaluate("rid('from').value='A';rid('amt').value='600';rid('cur').value='€';rdraw()");pg.wait_for_timeout(500)
    ok('alloc rate prefilled direct 1.1',pg.input_value('[data-ax=PST-0001]')=='1.1')
    pg.evaluate("document.querySelector('#r_alloc .fxSw').click()");pg.wait_for_timeout(500)
    ok('alloc rate flips to ~0.909091 with inverse placeholder',abs(float(pg.input_value('[data-ax=PST-0001]'))-1/1.1)<1e-5 and '1 $ = ? €' in pg.get_attribute('[data-ax=PST-0001]','placeholder'))
    pg.fill('[data-ax=PST-0001]','0.8');pg.wait_for_timeout(200)
    ok('typed inverse stored canonical 1.25',abs(float(pg.evaluate("R.alx['PST-0001'].rate"))-1.25)<1e-9)
    pg.evaluate("localStorage.setItem('pst_fxdir','d')")
    ok('no page errors',not errs)
    if errs:print(errs)
