import os;APP='file://'+os.environ.get('PST_HTML',os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','portist_invoice.html'))
from playwright.sync_api import sync_playwright
ok=lambda n,v:print(('PASS ' if v else 'FAIL ')+n)
with sync_playwright() as p:
    b=p.chromium.launch();pg=b.new_page(viewport={'width':1300,'height':900});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(APP);pg.wait_for_timeout(400)
    pg.evaluate("localStorage.setItem('pst_quick','1')")
    pg.fill('#lgName','م');pg.fill('#lgUser','admin');pg.fill('#lgPass','secret1');pg.fill('#lgPass2','secret1');pg.click('#lgGo');pg.wait_for_timeout(700)
    ok('dashboard is landing even with stale quick flag',pg.evaluate("S.mode")=='d' and pg.evaluate("location.hash")=='#/dashboard')
    pg.evaluate("routeTo('#/settings')");pg.wait_for_timeout(500)
    ok('settings nav has 9 sections for admin',pg.evaluate("document.querySelectorAll('#gNav button').length")==9)
    ok('window style select default modern',pg.input_value('#gMui')=='m' and not pg.evaluate("document.body.classList.contains('mui-c')"))
    pg.click('#bUsers');pg.wait_for_timeout(300)
    r=pg.evaluate("getComputedStyle(document.querySelector('#mUsers .mp')).borderRadius")
    ok('modern modal radius 18px',r=='18px')
    pg.click('#mUsers .mh [data-close]');pg.select_option('#gMui','c');pg.click('#bUsers');pg.wait_for_timeout(300)
    ok('classic keeps old radius',pg.evaluate("getComputedStyle(document.querySelector('#mUsers .mp')).borderRadius")=='14px')
    pg.reload();pg.wait_for_timeout(500)
    ok('classic choice persisted',pg.evaluate("document.body.classList.contains('mui-c')"))
    ok('no page errors',not errs)
    if errs:print(errs)
    b.close()
