import os;APP='file://'+os.environ.get('PST_HTML',os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','portist_invoice.html'))
from playwright.sync_api import sync_playwright
ok=lambda n,v:print(('PASS ' if v else 'FAIL ')+n)
def login(pg):
    pg.goto(APP);pg.wait_for_timeout(500)
    pg.fill('#lgName','م');pg.fill('#lgUser','admin');pg.fill('#lgPass','secret1');pg.fill('#lgPass2','secret1');pg.click('#lgGo');pg.wait_for_timeout(500)
with sync_playwright() as p:
    b=p.chromium.launch()
    pg=b.new_page(viewport={'width':1300,'height':900});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    login(pg)
    ok('sidebar visible desktop',pg.is_visible('#side') and not pg.is_visible('.bar .tabs'))
    pg.click('#sd_a');pg.wait_for_timeout(300);ok('sd accounting',pg.is_visible('#awrap') and 'on' in pg.get_attribute('#sd_a','class'))
    pg.click('#sd_ar');pg.wait_for_timeout(300);ok('sd receipts sub',pg.is_visible('#aRcP') and 'on' in pg.get_attribute('#sd_ar','class'))
    pg.click('#sd_c');pg.wait_for_timeout(300);ok('sd customers',pg.is_visible('#cwrap'))
    pg.click('#sd_g');pg.wait_for_timeout(300);ok('sd settings',pg.is_visible('#gwrap'))
    pg.click('#sd_h');pg.wait_for_timeout(300);ok('sd shipments',pg.is_visible('#hwrap'))
    w0=pg.evaluate("document.getElementById('side').offsetWidth");pg.click('#sd_t');pg.wait_for_timeout(200)
    ok('collapse',pg.evaluate("document.getElementById('side').offsetWidth")<w0)
    cols0=pg.evaluate("localStorage.getItem('pst_cols')")
    # quick mode on a phone-size viewport
    pg.set_viewport_size({'width':390,'height':844});pg.click('#bMore') if pg.is_visible('#bMore') else None
    pg.click('#bQuick');pg.wait_for_timeout(400)
    ok('quick shows only quick ui',pg.is_visible('#qwrap') and not pg.is_visible('.bar') and pg.is_visible('#qbar'))
    pg.fill('#qi_c','عميل سريع')
    pg.fill('#qi_rows .qrow:nth-child(1) [data-f=n]','قماش');pg.fill('#qi_rows .qrow:nth-child(1) [data-f=q]','10');pg.fill('#qi_rows .qrow:nth-child(1) [data-f=p]','25')
    pg.click('#qi_add');pg.fill('#qi_rows .qrow:nth-child(3) [data-f=n]','خدمة');pg.fill('#qi_rows .qrow:nth-child(3) [data-f=p]','50')
    ok('total live',pg.inner_text('#qi_t').startswith('300'))
    pg.click('#qi_go');pg.wait_for_timeout(1000)
    ok('preview shown',pg.evaluate("S.mode")=='i' and pg.is_visible('#qact') and pg.is_visible('#sheet'))
    d=pg.evaluate("(()=>{const D=LS.get('pst_inv',{});const k=Object.keys(D);return D[k[0]]})()")
    ok('invoice saved total 300 sent',d['t']==300 and d['st']=='sent' and d['rcv']=='عميل سريع' and len(d['rows'])==2)
    ok('preview form not editable/visible',not pg.is_visible('#sheet .addrow'))
    pg.screenshot(path='/tmp/s/q_prev.png')
    pg.click('#qaNew');pg.wait_for_timeout(300);ok('back to form',pg.is_visible('#qwrap'))
    pg.click('#qTR');pg.fill('#qr_c','عميل سريع');pg.fill('#qr_a','120');pg.click('#qr_go');pg.wait_for_timeout(1000)
    r=pg.evaluate("Object.values(LS.get('pst_rc',{}))[0]")
    ok('receipt saved',r and r['t']==120 and r['rcv']=='عميل سريع' and pg.evaluate("S.mode")=='r' and pg.is_visible('#rsheet'))
    pg.click('#qaNew');pg.wait_for_timeout(300)
    ok('recent list',pg.locator('#qRecent .qrc').count()==1)
    ok('validation blocks empty',True)
    pg.click('#qTI');pg.fill('#qi_c','');pg.click('#qi_go');pg.wait_for_timeout(200);ok('empty customer refused',pg.is_visible('#qwrap') and len(pg.evaluate("Object.keys(LS.get('pst_inv',{}))") )==1)
    ok('full-mode columns untouched',pg.evaluate("localStorage.getItem('pst_cols')")==cols0)
    pg.click('#qExit');pg.wait_for_timeout(500)
    ok('exit quick',not pg.evaluate("document.body.classList.contains('quick')") and pg.evaluate("S.cols.find(c=>c.id==='qty').v")==0)
    pg.reload();pg.wait_for_timeout(700)
    ok('reload no errors',not errs);print(errs)
    b.close()
