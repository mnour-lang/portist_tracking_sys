import os;APP='file://'+os.environ.get('PST_HTML',os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','portist_invoice.html'))
from playwright.sync_api import sync_playwright
ok=lambda n,v:print(('PASS ' if v else 'FAIL ')+n)
with sync_playwright() as p:
    b=p.chromium.launch();pg=b.new_page(viewport={'width':1300,'height':900});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(APP);pg.wait_for_timeout(400)
    pg.fill('#lgName','م');pg.fill('#lgUser','admin');pg.fill('#lgPass','secret1');pg.fill('#lgPass2','secret1');pg.click('#lgGo');pg.wait_for_timeout(600)
    pg.evaluate("""()=>{LS.set('pst_revpol','inv');SHS.set({'SH-1':{code:'SH-1',cur:'$',date:'2026-01-01',st:'ld',hist:[],
      costs:[{id:'a',type:'تخليص جمركي',amt:400,cur:'$',sup:'مورد',pd:false},{id:'b',type:'نقل داخلي',amt:100,cur:'$',sup:'مورد',pd:true,pdDate:'2026-01-02'}],
      cons:[{id:'c1',cust:'A',cbm:1,pk:1}]}})}""")
    T=pg.evaluate("shFin(SHS.get()['SH-1']).T")
    ok('legacy pd:true counts as fully paid',T['paid']==100 and T['unpaid']==400)
    pg.evaluate("routeTo('#/costs/shipment/SH-1')");pg.wait_for_timeout(900)
    pg.click('tr[data-lid=a] [data-ca=pay]');pg.wait_for_timeout(300)
    ok('modal opens with remaining prefilled 400',pg.input_value('#cp_amt')=='400')
    pg.fill('#cp_amt','150');pg.fill('#cp_note','تحويل');pg.click('#cp_save');pg.wait_for_timeout(700)
    c=pg.evaluate("SHS.get()['SH-1'].costs[0]")
    ok('partial payment stored; not fully paid',len(c['pays'])==1 and c['pd'] is False)
    T=pg.evaluate("shFin(SHS.get()['SH-1']).T")
    ok('T.paid = 150+100, unpaid 250',T['paid']==250 and T['unpaid']==250)
    ok('modal shows remaining 250 after refresh',pg.input_value('#cp_amt')=='250')
    pg.fill('#cp_amt','300');pg.click('#cp_save');pg.wait_for_timeout(400)
    ok('overpayment refused',pg.evaluate("SHS.get()['SH-1'].costs[0].pays.length")==1)
    pg.fill('#cp_amt','250');pg.click('#cp_save');pg.wait_for_timeout(700)
    c=pg.evaluate("SHS.get()['SH-1'].costs[0]")
    ok('final payment marks fully paid',c['pd'] is True and len(c['pays'])==2 and c['pdDate'])
    pg.click('[data-pdel]');pg.click('[data-pdel]');pg.wait_for_timeout(800)
    ok('deleting a payment reopens balance',pg.evaluate("SHS.get()['SH-1'].costs[0].pd")is False)
    pg.click('#mPay [data-close].b2')
    # checkbox toggles
    pg.evaluate("routeTo('#/costs/suppliers')");pg.wait_for_timeout(700)
    ok('supplier unpaid shows remaining (not full)',('150' in pg.inner_text('#cc')) or ('250' in pg.inner_text('#cc')))
    pg.click('[data-ca=suppay]');pg.click('[data-ca=suppay]');pg.wait_for_timeout(1200)
    ok('pay-all settles remaining only',pg.evaluate("shFin(SHS.get()['SH-1']).T.unpaid")==0)
    pg.evaluate("routeTo('#/costs/ledger')");pg.wait_for_timeout(700)
    pg.evaluate("document.querySelector('tr[data-lid=a] [data-cpd]').click()");pg.wait_for_timeout(700)
    ok('unchecking clears payments',pg.evaluate("SHS.get()['SH-1'].costs[0].pd")is False and pg.evaluate("shFin(SHS.get()['SH-1']).T.unpaid")==400)
    ok('no page errors',not errs)
    if errs:print(errs)
    b.close()
